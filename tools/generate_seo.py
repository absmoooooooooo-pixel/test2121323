#!/usr/bin/env python3
"""Generate robots.txt, sitemap.xml and the per-page SEO head block.

Run this after adding, removing or renaming a page, or after changing the
domain:

    python tools/generate_seo.py

The script is idempotent: the SEO block it writes into every page is wrapped
in <!-- SEO:START --> markers, so running it again replaces the block instead
of adding a second one. Titles and meta descriptions are authored inside each
page and are only read here, never rewritten.
"""
from __future__ import annotations

import datetime as dt
import html as html_module
import json
import re
from pathlib import Path

# ---------------------------------------------------------------------------
# SITE CONFIGURATION
# Change SITE_BASE if the website is published on a different host. Every
# canonical URL, Open Graph URL, sitemap entry and robots.txt sitemap line is
# built from this single value.
# ---------------------------------------------------------------------------
SITE_BASE = "https://metalweightcalculator.online"

SITE_NAME = "Metal Weight Calculator"
SITE_LANGUAGE = "en"
SOCIAL_IMAGE = "icons/icon-512.png"
SOCIAL_IMAGE_ALT = "Metal Weight Calculator"

# The site files live in frontend/ after the frontend/backend split.
ROOT = Path(__file__).resolve().parent.parent / "frontend"
ROBOTS = ROOT / "robots.txt"
SITEMAP = ROOT / "sitemap.xml"

START_MARKER = "<!-- SEO:START (generated by tools/generate_seo.py) -->"
END_MARKER = "<!-- SEO:END -->"


# ---------------------------------------------------------------------------
# PAGE DISCOVERY
# Every index.html in the project is a public page, except inside folders that
# only hold styles, scripts, images, build tools or app data. A folder without
# an index.html is never listed, so no broken route can reach the sitemap.
# ---------------------------------------------------------------------------
SKIP_FOLDERS = {
    "assets",
    "dist",
    "BIN",
    "icons",
    "shared",
    "scripts",
    "tools",
    "node_modules",
    ".git",
    ".freebuff",
    ".cloud-attachments",
}


def find_pages() -> list[Path]:
    pages = [ROOT / "index.html"]

    for page in sorted(ROOT.rglob("index.html"), key=lambda item: item.as_posix().lower()):
        relative = page.relative_to(ROOT)

        if relative.as_posix() == "index.html":
            continue
        if any(part in SKIP_FOLDERS or part.startswith(".") for part in relative.parts[:-1]):
            continue

        pages.append(page)

    return pages


def url_for(page: Path) -> str:
    """Absolute canonical URL for a page file (home page maps to the root)."""
    relative = page.relative_to(ROOT).as_posix()

    if relative == "index.html":
        return SITE_BASE + "/"

    return SITE_BASE + "/" + relative


def read_tag(html: str, pattern: str) -> str:
    match = re.search(pattern, html, re.S | re.I)
    # The tag is read from HTML but written back into an attribute, so entities
    # such as &amp; are decoded first and escaped exactly once.
    return html_module.unescape(match.group(1).strip()) if match else ""


def page_details(page: Path) -> dict:
    html = page.read_text(encoding="utf-8")

    title = read_tag(html, r"<title>(.*?)</title>")
    description = read_tag(
        html,
        r'<meta\s+name="description"\s+content="(.*?)"',
    )
    heading = read_tag(html, r"<h1[^>]*>(.*?)</h1>")
    heading = re.sub(r"<[^>]+>", "", heading)
    heading = re.sub(r"\s+", " ", heading).strip()

    return {
        "path": page,
        "url": url_for(page),
        "title": title,
        "description": description,
        "heading": heading or title,
        "kind": page_kind(page),
    }


def page_kind(page: Path) -> str:
    relative = page.relative_to(ROOT).as_posix()

    if relative == "index.html":
        return "home"
    if relative.startswith("about/"):
        return "about"
    return "calculator"


# ---------------------------------------------------------------------------
# STRUCTURED DATA
# Only facts taken from the page itself are published: name, URL, description
# and language. No ratings, reviews, prices or business details are invented.
# ---------------------------------------------------------------------------
def structured_data(details: dict) -> dict:
    organization_id = SITE_BASE + "/#organization"
    website_id = SITE_BASE + "/#website"

    organization = {
        "@type": "Organization",
        "@id": organization_id,
        "name": SITE_NAME,
        "url": SITE_BASE + "/",
        "logo": {
            "@type": "ImageObject",
            "url": SITE_BASE + "/" + SOCIAL_IMAGE,
            "width": 512,
            "height": 512,
        },
    }

    website = {
        "@type": "WebSite",
        "@id": website_id,
        "url": SITE_BASE + "/",
        "name": SITE_NAME,
        "inLanguage": SITE_LANGUAGE,
        "publisher": {"@id": organization_id},
    }

    if details["kind"] == "home":
        return {
            "@context": "https://schema.org",
            "@graph": [organization, website],
        }

    graph = [organization, website]

    if details["kind"] == "about":
        graph.append(
            {
                "@type": "AboutPage",
                "@id": details["url"] + "#webpage",
                "url": details["url"],
                "name": details["title"],
                "description": details["description"],
                "inLanguage": SITE_LANGUAGE,
                "isPartOf": {"@id": website_id},
                "about": {"@id": organization_id},
            }
        )
        crumbs = [
            ("Home", SITE_BASE + "/"),
            ("About Us", details["url"]),
        ]
    else:
        # An interactive calculator is a web application, not a downloadable
        # app: no price, rating or store information is claimed.
        graph.append(
            {
                "@type": "WebApplication",
                "@id": details["url"] + "#webapp",
                "url": details["url"],
                "name": details["heading"],
                "description": details["description"],
                "applicationCategory": "UtilitiesApplication",
                "operatingSystem": "Any",
                "browserRequirements": "Requires JavaScript",
                "isAccessibleForFree": True,
                "inLanguage": SITE_LANGUAGE,
                "isPartOf": {"@id": website_id},
                "publisher": {"@id": organization_id},
            }
        )
        crumbs = [
            ("Home", SITE_BASE + "/"),
            (details["heading"], details["url"]),
        ]

    graph.append(
        {
            "@type": "BreadcrumbList",
            "@id": details["url"] + "#breadcrumb",
            "itemListElement": [
                {
                    "@type": "ListItem",
                    "position": index + 1,
                    "name": name,
                    "item": url,
                }
                for index, (name, url) in enumerate(crumbs)
            ],
        }
    )

    return {"@context": "https://schema.org", "@graph": graph}


def json_ld_block(details: dict) -> str:
    payload = json.dumps(structured_data(details), ensure_ascii=False, indent=2)
    # "</" inside a script element would close it early.
    payload = payload.replace("</", "<\\/")

    return '<script type="application/ld+json">\n' + payload + "\n</script>"


# ---------------------------------------------------------------------------
# HEAD BLOCK
# ---------------------------------------------------------------------------
def head_block(details: dict) -> str:
    url = details["url"]
    title = details["title"]
    description = details["description"]
    image = SITE_BASE + "/" + SOCIAL_IMAGE

    def escape(value: str) -> str:
        return (
            value.replace("&", "&amp;")
            .replace('"', "&quot;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
        )

    lines = [
        START_MARKER,
        f'    <link rel="canonical" href="{escape(url)}">',
        '    <meta property="og:type" content="website">',
        f'    <meta property="og:site_name" content="{escape(SITE_NAME)}">',
        f'    <meta property="og:title" content="{escape(title)}">',
        f'    <meta property="og:description" content="{escape(description)}">',
        f'    <meta property="og:url" content="{escape(url)}">',
        f'    <meta property="og:image" content="{escape(image)}">',
        f'    <meta property="og:image:alt" content="{escape(SOCIAL_IMAGE_ALT)}">',
        '    <meta name="twitter:card" content="summary">',
        f'    <meta name="twitter:title" content="{escape(title)}">',
        f'    <meta name="twitter:description" content="{escape(description)}">',
        f'    <meta name="twitter:image" content="{escape(image)}">',
        json_ld_block(details),
        END_MARKER,
    ]

    return "\n".join(lines)


def page_with_head_block(page: Path, details: dict) -> bool:
    html = page.read_text(encoding="utf-8")

    block = head_block(details)

    # Remove a block written by an earlier run.
    html = re.sub(
        re.escape(START_MARKER) + r".*?" + re.escape(END_MARKER) + r"\n?",
        "",
        html,
        flags=re.S,
    )

    if "</head>" not in html:
        print(f"SKIP (no </head>): {page.relative_to(ROOT)}")
        return False

    html = html.replace("</head>", block + "\n</head>", 1)
    page.write_text(html, encoding="utf-8")
    return True


# ---------------------------------------------------------------------------
# ROBOTS.TXT
# Private/build-only folders are excluded; CSS, JavaScript and images stay
# crawlable so Google can render the pages.
# ---------------------------------------------------------------------------
def write_robots() -> None:
    content = f"""# robots.txt for {SITE_BASE}
# CSS, JavaScript and image folders are deliberately left crawlable so search
# engines can render every calculator page.

User-agent: *
Allow: /
Disallow: /tools/
Disallow: /.freebuff/
Disallow: /.cloud-attachments/
Disallow: /*.log$

# AdSense crawlers. Mediapartners-Google reads page content to match ads,
# AdsBot-Google checks landing pages. Both must be allowed on every page.
User-agent: Mediapartners-Google
Allow: /

User-agent: AdsBot-Google
Allow: /

Sitemap: {SITE_BASE}/sitemap.xml
"""
    ROBOTS.write_text(content, encoding="utf-8", newline="\n")


# ---------------------------------------------------------------------------
# SITEMAP.XML
# 25 pages is far below the 50,000-URL limit, so one sitemap is enough; a
# sitemap index would only add another file to fetch.
# ---------------------------------------------------------------------------
def write_sitemap(pages: list[dict]) -> None:
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ]

    for details in pages:
        # Real file modification date, not a generated or invented date.
        stamp = dt.date.fromtimestamp(
            details["path"].stat().st_mtime
        ).isoformat()

        lines.append("  <url>")
        lines.append(f"    <loc>{details['url']}</loc>")
        lines.append(f"    <lastmod>{stamp}</lastmod>")
        lines.append("  </url>")

    lines.append("</urlset>")

    SITEMAP.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main() -> None:
    pages = [page_details(page) for page in find_pages()]

    written = 0
    for details in pages:
        if page_with_head_block(details["path"], details):
            written += 1

    write_robots()
    write_sitemap(pages)

    print(f"Head block written: {written}/{len(pages)} pages")
    print(f"robots.txt: {ROBOTS.relative_to(ROOT)}")
    print(f"sitemap.xml: {len(pages)} URLs")


if __name__ == "__main__":
    main()
